import pandas as pd
import numpy as np

def generate_dataset(n=1700, seed=42):
    np.random.seed(seed)

    # ---------------------------
    # USER INPUT FEATURES
    # ---------------------------

    # Team
    team_size = np.random.randint(4, 10, n)

    # Planning
    planned_story_points = np.random.randint(25, 80, n)
    sprint_duration_days = np.random.choice([10, 14], n)
    total_tasks = np.random.randint(12, 35, n)

    # high priority <= 40% of tasks
    high_priority_tasks = np.array([
    np.random.randint(1, max(2, int(0.4 * t) + 1))
    for t in total_tasks
])

    # History
    previous_sprint_velocity = (
        planned_story_points * np.random.uniform(0.6, 1.0, n)
    ).round().astype(int)

    previous_planned_story_points = np.random.randint(25, 80, n)

    previous_completed_story_points = (
        previous_planned_story_points * np.random.uniform(0.6, 1.1, n)
    ).round().astype(int)

    bugs_reported_previous_sprint = np.random.randint(0, 15, n)

    carry_over_story_points = (
        planned_story_points * np.random.uniform(0, 0.3, n)
    ).round().astype(int)

    # ---------------------------
    # DERIVED FEATURES
    # ---------------------------

    velocity_ratio = planned_story_points / (previous_sprint_velocity + 1)

    workload_per_developer = total_tasks / team_size

    carry_over_ratio = carry_over_story_points / (planned_story_points + 1)

    # ---------------------------
    # BUFFER / BEHAVIOR FEATURES
    # ---------------------------

    estimation_accuracy = previous_completed_story_points / (
        previous_planned_story_points + 1
    )

    buffer_ratio_previous = np.maximum(
    (previous_planned_story_points - previous_completed_story_points) /
    (previous_planned_story_points + 1),
    0
)

    # simulate variance (based on behavior)
    estimation_variance = np.abs(np.random.normal(0.1, 0.05, n))
    estimation_variance = np.clip(estimation_variance, 0, 0.25)

    # ---------------------------
    # TARGET GENERATION (LOGIC-BASED)
    # ---------------------------

    risk_score = (
        (velocity_ratio - 1) * 2
        + carry_over_ratio * 2
        + (workload_per_developer - 3) * 0.8
        + (bugs_reported_previous_sprint / 10)
        + estimation_variance
    )

    # buffer reduces risk
    risk_score -= np.where(estimation_accuracy < 0.85, 0.8, 0)
    risk_score += np.where(estimation_accuracy > 1.05, 0.8, 0)

    # noise
    risk_score += np.random.normal(0, 0.5, n)

    # convert to probability
    probability = 1 / (1 + np.exp(-risk_score))

    threshold = np.percentile(probability, 60)  # adjust here

    sprint_success = np.where(probability < threshold, 1, 0)

    # ---------------------------
    # CREATE DATAFRAME
    # ---------------------------

    df = pd.DataFrame({
        "team_size": team_size,
        "planned_story_points": planned_story_points,
        "sprint_duration_days": sprint_duration_days,
        "total_tasks": total_tasks,
        "high_priority_tasks": high_priority_tasks,

        "previous_sprint_velocity": previous_sprint_velocity,
        "previous_planned_story_points": previous_planned_story_points,
        "previous_completed_story_points": previous_completed_story_points,
        "bugs_reported_previous_sprint": bugs_reported_previous_sprint,
        "carry_over_story_points": carry_over_story_points,

        "velocity_ratio": velocity_ratio,
        "workload_per_developer": workload_per_developer,
        "carry_over_ratio": carry_over_ratio,

        "estimation_accuracy": estimation_accuracy,
        "buffer_ratio_previous": buffer_ratio_previous,
        "estimation_variance": estimation_variance,

        "sprint_success": sprint_success
    })

    return df


